//! Embeds the application icon (resource 1, also the tray icon) and the
//! manifest: per-monitor DPI awareness and common controls 6. Also turns the
//! string tables in `locales/` into the compact form `src/i18n.rs` embeds.
use std::collections::BTreeMap;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=icons/icon.ico");
    println!("cargo:rerun-if-changed=app.manifest");
    println!("cargo:rerun-if-changed=locales");
    tables();
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let mut resource = winresource::WindowsResource::new();
        resource.set_icon("icons/icon.ico");
        resource.set_manifest(include_str!("app.manifest"));
        resource.compile().expect("compile Windows resources");
    }
}

/// Reads `locales/Resources[.culture].resx` and `locales/Native[.culture].resx`
/// and writes `i18n.rs` (the sorted key list and the culture index) and
/// `i18n.bin` (each culture's entries: key index u16, byte length u16 and the
/// UTF-8 text, little endian) to OUT_DIR. The neutral table has every key;
/// the others only what they translate.
fn tables() {
    let dir = Path::new("locales");
    let mut cultures: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    let mut files: Vec<_> = std::fs::read_dir(dir)
        .expect("read locales")
        .map(|e| e.expect("locales entry").path())
        .filter(|p| p.extension().is_some_and(|e| e == "resx"))
        .collect();
    files.sort();
    for path in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        let stem = path.file_stem().unwrap().to_str().unwrap();
        let (base, culture) = match stem.split_once('.') {
            Some((base, culture)) => (base, culture.to_ascii_lowercase()),
            None => (stem, String::new()),
        };
        assert!(
            base == "Resources" || base == "Native",
            "unexpected table {}",
            path.display()
        );
        let text = std::fs::read_to_string(path).expect("read resx");
        let entries = parse_resx(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let table = cultures.entry(culture).or_default();
        for (key, value) in entries {
            if table.insert(key.clone(), value).is_some() {
                panic!("{}: duplicate key {key}", path.display());
            }
        }
    }
    let neutral = cultures.remove("").expect("locales/Resources.resx");
    let keys: Vec<&String> = neutral.keys().collect();
    assert!(keys.len() < usize::from(u16::MAX));
    let index = |key: &str| keys.binary_search_by(|k| k.as_str().cmp(key)).ok();

    let mut blob = Vec::new();
    let mut put = |entries: &mut dyn Iterator<Item = (usize, &String)>| {
        let start = blob.len();
        for (id, value) in entries {
            let len = u16::try_from(value.len()).expect("string too long");
            blob.extend_from_slice(&(id as u16).to_le_bytes());
            blob.extend_from_slice(&len.to_le_bytes());
            blob.extend_from_slice(value.as_bytes());
        }
        (start, blob.len())
    };
    let mut index_rs = Vec::new();
    index_rs.push((String::new(), put(&mut neutral.values().enumerate())));
    for (culture, table) in &cultures {
        for key in table.keys() {
            if index(key).is_none() {
                println!("cargo:warning={culture}: key {key} is not in the neutral table");
            }
        }
        // What the culture would show without its own entry: its nearest
        // parent table's, else neutral. Equal entries are left out.
        let parents: Vec<&BTreeMap<String, String>> = parents(culture)
            .iter()
            .filter_map(|p| cultures.get(p))
            .collect();
        let inherited = |key: &str| {
            parents
                .iter()
                .find_map(|t| t.get(key))
                .or_else(|| neutral.get(key))
        };
        let range = put(&mut table.iter().filter_map(|(key, value)| {
            let id = index(key)?;
            (inherited(key) != Some(value)).then_some((id, value))
        }));
        index_rs.push((culture.clone(), range));
    }

    let mut rs = String::from("// Generated by build.rs from locales/*.resx.\n");
    rs.push_str(&format!("pub static KEYS: [&str; {}] = [\n", keys.len()));
    for key in &keys {
        rs.push_str(&format!("    {key:?},\n"));
    }
    rs.push_str("];\n");
    rs.push_str(&format!(
        "/// Culture name (lower case, \"\" neutral) and its byte range in the blob.\n\
         pub static CULTURES: [(&str, u32, u32); {}] = [\n",
        index_rs.len()
    ));
    for (culture, (start, end)) in &index_rs {
        rs.push_str(&format!("    ({culture:?}, {start}, {end}),\n"));
    }
    rs.push_str("];\n");
    let out = std::env::var("OUT_DIR").expect("OUT_DIR");
    std::fs::write(Path::new(&out).join("i18n.rs"), rs).expect("write i18n.rs");
    std::fs::write(Path::new(&out).join("i18n.bin"), blob).expect("write i18n.bin");
}

/// "bs-latn-ba" -> ["bs-latn", "bs"], as `src/i18n.rs` falls back.
fn parents(culture: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut current = culture.to_owned();
    while let Some(at) = current.rfind('-') {
        current.truncate(at);
        out.push(current.clone());
    }
    out
}

/// The string `<data>` entries of a .resx document: name and value, with
/// comments skipped, entities decoded and line ends normalised like an XML
/// parser. Entries with a `type` or `mimetype` (non-strings) are left out.
fn parse_resx(text: &str) -> Result<Vec<(String, String)>, String> {
    let mut out = Vec::new();
    let mut rest = text;
    while let Some(at) = rest.find('<') {
        rest = &rest[at..];
        if let Some(body) = rest.strip_prefix("<!--") {
            let end = body.find("-->").ok_or("unterminated comment")?;
            rest = &body[end + 3..];
            continue;
        }
        if !rest.starts_with("<data ") {
            rest = &rest[1..];
            continue;
        }
        let tag_end = rest.find('>').ok_or("unterminated <data>")?;
        let tag = &rest[..tag_end];
        let self_closing = tag.ends_with('/');
        let name = attribute(tag, "name").ok_or("<data> without name")?;
        let typed = attribute(tag, "type").is_some() || attribute(tag, "mimetype").is_some();
        rest = &rest[tag_end + 1..];
        if self_closing {
            continue;
        }
        let end = rest.find("</data>").ok_or("unterminated <data>")?;
        let body = &rest[..end];
        rest = &rest[end + 7..];
        if typed {
            continue;
        }
        let value = if let Some(start) = body.find("<value>") {
            let inner = &body[start + 7..];
            let stop = inner.find("</value>").ok_or("unterminated <value>")?;
            decode(&inner[..stop])?
        } else if body.contains("<value/>") || body.contains("<value />") {
            String::new()
        } else {
            return Err(format!("{name}: no <value>"));
        };
        out.push((decode(&name)?, value));
    }
    Ok(out)
}

fn attribute(tag: &str, name: &str) -> Option<String> {
    let mut search = tag;
    loop {
        let at = search.find(name)?;
        let before = search[..at].chars().last();
        let after = &search[at + name.len()..];
        search = after;
        if before.is_some_and(|c| c.is_whitespace()) {
            if let Some(after) = after.trim_start().strip_prefix('=') {
                let after = after.trim_start();
                let quote = after.chars().next()?;
                let value = &after[1..];
                return Some(value[..value.find(quote)?].to_owned());
            }
        }
    }
}

fn decode(text: &str) -> Result<String, String> {
    let text = text.replace("\r\n", "\n").replace('\r', "\n");
    let mut out = String::with_capacity(text.len());
    let mut rest = text.as_str();
    while let Some(at) = rest.find('&') {
        out.push_str(&rest[..at]);
        let semi = rest[at..].find(';').ok_or("bad entity")? + at;
        let entity = &rest[at + 1..semi];
        match entity {
            "amp" => out.push('&'),
            "lt" => out.push('<'),
            "gt" => out.push('>'),
            "quot" => out.push('"'),
            "apos" => out.push('\''),
            _ => {
                let code = if let Some(hex) = entity.strip_prefix("#x") {
                    u32::from_str_radix(hex, 16)
                } else if let Some(dec) = entity.strip_prefix('#') {
                    dec.parse()
                } else {
                    return Err(format!("unknown entity &{entity};"));
                };
                let c = code
                    .ok()
                    .and_then(char::from_u32)
                    .ok_or_else(|| format!("bad character reference &{entity};"))?;
                out.push(c);
            }
        }
        rest = &rest[semi + 1..];
    }
    out.push_str(rest);
    Ok(out)
}
